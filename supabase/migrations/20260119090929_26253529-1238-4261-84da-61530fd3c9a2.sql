-- Create helper functions for checking specific roles
CREATE OR REPLACE FUNCTION public.is_seller(_user_id uuid DEFAULT auth.uid())
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.user_roles
    WHERE user_id = _user_id AND role = 'seller'
  )
$$;

